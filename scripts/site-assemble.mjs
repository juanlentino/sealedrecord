/* Assemble the static verifier into dist-site/ from three sources: site/
   (the page), the npm tarball of this library (what consumers install), and
   the conformance vectors, inlined so the example buttons make no request.

   --local packs the working tree; without it the tarball comes from the
   registry at package.json's version, which is what the Pages deploy does.
   Either way the page imports ./sealedrecord/index.js, never ../index.js.
   Run: node scripts/site-assemble.mjs [--local] */

import { mkdirSync, rmSync, cpSync, readFileSync, writeFileSync, readdirSync, lstatSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const OUT = `${ROOT}dist-site/`;
const local = process.argv.includes("--local");
const { name, version } = JSON.parse(readFileSync(`${ROOT}package.json`, "utf8"));

rmSync(OUT, { recursive: true, force: true });
mkdirSync(`${OUT}tmp`, { recursive: true });

/* 1. The page, minus the dev symlink that points at the checkout. */
for (const f of readdirSync(`${ROOT}site`)) {
  if (lstatSync(`${ROOT}site/${f}`).isSymbolicLink()) continue;
  cpSync(`${ROOT}site/${f}`, `${OUT}${f}`, { recursive: true });
}

/* 2. The library, from its tarball. */
const spec = local ? ROOT : `${name}@${version}`;
const packed = execFileSync("npm", ["pack", spec, "--pack-destination", `${OUT}tmp`, "--silent"], { cwd: ROOT, encoding: "utf8" }).trim();
execFileSync("tar", ["-xzf", `${OUT}tmp/${packed.split("\n").pop()}`, "-C", `${OUT}tmp`]);
cpSync(`${OUT}tmp/package`, `${OUT}sealedrecord`, { recursive: true });
rmSync(`${OUT}tmp`, { recursive: true, force: true });

/* 3. The vectors, inlined. */
const b64 = (p) => readFileSync(`${ROOT}vectors/${p}`).toString("base64");
writeFileSync(`${OUT}vectors.js`, [
  "/* Generated by scripts/site-assemble.mjs from vectors/. Do not edit. */",
  `export const RECORD = ${readFileSync(`${ROOT}vectors/record.json`, "utf8").trim()};`,
  `export const TAKE_WAV = "${b64("take.wav")}";`,
  `export const TAKE_RETAGGED_WAV = "${b64("take-retagged.wav")}";`,
  "",
].join("\n"));

const shipped = JSON.parse(readFileSync(`${OUT}sealedrecord/package.json`, "utf8")).version;
writeFileSync(`${OUT}version.js`, `export const VERSION = "${shipped}";\n`);
console.log(`dist-site assembled: ${name}@${shipped} from ${local ? "the working tree" : "the registry"}`);
